/* VOLE hash controller. x_data_in order: x0, x1..x_degmax, then four tail words. */
module vole_hash_controller #(
    parameter DATA_WIDTH = 128
)(
    input wire CLK, RST_N, start_in, x_valid_in, mul_done_in,
    input wire [15:0] step_cnt_in, deg_max_in,
    output reg load_x_out, fetch_x_out, mul_start_out,
    output reg update_y_out, update_h_out, x_ready_out, done_out,
    output wire [2:0] state_out
);
    localparam [2:0] S_IDLE=0, S_LOAD_X0=1, S_FETCH_X=2,
                     S_MUL_START=3, S_MUL_WAIT=4, S_FIN_START=5,
                     S_FIN_WAIT=6, S_DONE=7;
    reg [2:0] state_r, next_state;
    reg [2:0] tail_count;
    reg [2:0] next_tail_count;
    reg final_started;

    always @* begin
        next_state=state_r;
        next_tail_count=tail_count;
        load_x_out=0; fetch_x_out=0; mul_start_out=0;
        update_y_out=0; update_h_out=0; x_ready_out=0; done_out=0;
        case (state_r)
          S_IDLE: if (start_in) next_state=S_LOAD_X0;
          S_LOAD_X0: begin
            x_ready_out=1;
            if (x_valid_in) begin load_x_out=1; next_state=S_FETCH_X; end
          end
          S_FETCH_X: begin
            x_ready_out=1;
            if (x_valid_in) begin fetch_x_out=1; next_state=S_MUL_START; end
          end
          S_MUL_START: begin mul_start_out=1; next_state=S_MUL_WAIT; end
          S_MUL_WAIT: if (mul_done_in) begin
            update_y_out=1;
            if (step_cnt_in == deg_max_in) begin
              next_tail_count=0; next_state=S_FIN_START;
            end else next_state=S_FETCH_X;
          end
          /* Read and retain four x tail words before computing h in parallel. */
          S_FIN_START: begin
            x_ready_out=1;
            if (x_valid_in) begin
              fetch_x_out=1;
              if (tail_count == 3) next_state=S_FIN_WAIT;
              else next_tail_count=tail_count+1'b1;
            end
          end
          S_FIN_WAIT: begin
            /* A one-cycle start pulse is generated by the state transition. */
            if (!final_started) mul_start_out=1;
            else if (mul_done_in) begin update_h_out=1; next_state=S_DONE; end
          end
          S_DONE: begin done_out=1; next_state=S_IDLE; end
          default: next_state=S_IDLE;
        endcase
    end

    always @(posedge CLK or negedge RST_N) begin
      if (!RST_N) begin state_r<=S_IDLE; tail_count<=0; final_started<=0; end
      else begin
        state_r<=next_state; tail_count<=next_tail_count;
        if (state_r != S_FIN_WAIT) final_started<=0;
        else if (!final_started) final_started<=1;
      end
    end
    assign state_out=state_r;
endmodule
